def _sch_font(size):
    """Regular sans-serif TrueType font (Liberation Sans if present)."""
    from PIL import ImageFont
    try:
        import matplotlib.font_manager as fm
        known = [f.fname for f in fm.fontManager.ttflist]
    except ImportError:
        known = []
    for name in SCH_FONTS:
        for path in [name] + [p for p in known if Path(p).name == name]:
            try:
                return ImageFont.truetype(path, size)
            except OSError:
                continue
    return ImageFont.load_default(size)


def _lcd_filter(a):
    """FIR-filter a (h, 3w) sub-pixel coverage map and fold it to (h, w, 3)."""
    k = len(LCD_FIR) // 2
    p = np.pad(a, ((0, 0), (k, k)))
    c = sum(wt * p[:, i:i + a.shape[1]] for i, wt in enumerate(LCD_FIR))
    return c.reshape(a.shape[0], a.shape[1] // 3, 3)


def draw_schematic(layout, diode_label, r_label, c_label, outpath):
    """Render one capture-style schematic PNG (no capacitor if c_label is None).

    Pixel-exact re-creation of the report's reference schematics: 1-px
    aliased wires (green) with blue pin stubs, blue junction discs, a grey
    dotted grid, and sub-pixel (LCD) antialiased blue labels."""
    from PIL import Image, ImageDraw

    W, H = layout["W"], SCH_H
    img = np.full((H, W, 3), 255, np.uint8)
    yy, xx = np.mgrid[0:H, 0:W]

    # -- pixel primitives (all coordinates and ranges inclusive) -------------
    def hline(y, x0, x1, col=SCH_GREEN):
        img[y, x0:x1 + 1] = col

    def vline(x, y0, y1, col=SCH_GREEN):
        img[y0:y1 + 1, x] = col

    def seg(x0, y0, x1, y1, col=SCH_GREEN, last=True):
        """Straight segment; ties round half down (matches the reference)."""
        n = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(n + (1 if last else 0)):
            t = i / n
            img[int(math.ceil(y0 + (y1 - y0) * t - .5)),
                int(math.ceil(x0 + (x1 - x0) * t - .5))] = col

    def disc(x, y, r=9):
        img[(xx - (x - .5)) ** 2 + (yy - (y - .5)) ** 2 <= r * r] = SCH_BLUE

    def blend(cov, x0, y0, color):
        """Composite per-channel (sub-pixel) coverage onto the image."""
        h, w, _ = cov.shape
        sub = img[y0:y0 + h, x0:x0 + w].astype(float)
        img[y0:y0 + h, x0:x0 + w] = np.rint(
            sub * (1 - cov) + np.array(color, float) * cov).astype(np.uint8)

    def text(s, x, base, color=SCH_BLUE):
        """Left-aligned label, baseline row `base`, hinted integer advances,
        3x horizontal oversampling and the FreeType LCD filter."""
        f1, f3 = _sch_font(SCH_TEXT_PX), _sch_font(SCH_TEXT_PX * 3)
        w = int(sum(round(f1.getlength(c)) for c in s)) + 12
        h = int(SCH_TEXT_PX * 1.4)
        top = base - int(SCH_TEXT_PX * 1.05)
        im = Image.new("L", (w * 3, h * 3), 0)
        d, cx = ImageDraw.Draw(im), 0.0
        for ch in s:
            d.text((round(cx + 6 * 3), (base - top) * 3), ch, font=f3,
                   fill=255, anchor="ls")
            cx += 3 * round(f1.getlength(ch))
        cov = np.asarray(im, float).reshape(h, 3, w * 3).mean(1) / 255.0
        blend(_lcd_filter(cov), x - 6, top, color)

    def rect_mark(xa, xb, ya, yb, x0, y0, w, h):
        """Sub-pixel filtered coverage of a continuous rectangle."""
        sx = np.arange(w * 3) / 3.0 + x0
        ox = np.clip(np.minimum(sx + 1 / 3, xb) - np.maximum(sx, xa), 0, None) * 3
        py = np.arange(h) + y0
        oy = np.clip(np.minimum(py + 1, yb) - np.maximum(py, ya), 0, None)
        return oy[:, None] * ox[None, :]

    # -- layout shorthands ---------------------------------------------------
    v1x, top_y, bot_y = layout["v1_x"], layout["top_y"], layout["bot_y"]
    ro, rm, rg = layout["row_out"], layout["row_mid"], layout["row_gnd"]
    vo, vm = layout["vx_out"], layout["vx_mid"]
    x0, x1 = layout["r_body"]

    # -- capture grid: single grey pixels, 44-px pitch (+1 px at the bridge) --
    gx, k = [], 0
    while True:
        x = v1x - 44 + 44 * k
        x += 1 if x >= vo - 1 else 0
        if x >= W:
            break
        gx.append(x)
        k += 1
    for y in range(top_y, H, 44):
        img[y, gx] = SCH_GRAY

    # -- source leads, outer rails -------------------------------------------
    vline(v1x, top_y, 330)
    vline(v1x, 331, 373, SCH_BLUE)
    vline(v1x, 463, 506, SCH_BLUE)
    vline(v1x, 507, bot_y)
    hline(top_y, v1x, layout["top_drop_x"])
    vline(layout["top_drop_x"], top_y, ro)
    hline(bot_y, v1x, layout["dot_bot"])
    vline(layout["dot_bot"], rg, bot_y)
    vline(vo, ro, rg)
    vline(vm, ro, rg)

    # -- the two diode rows: wire, blue pin stubs, triangle and cathode bar ---
    def diode_row(y, di, dj, dot_x, lbl_i, lbl_j, bottom):
        hline(y, vo, di[0])
        hline(y, di[1], dj[0])
        hline(y, dj[1], vm)
        # pin stubs (blue): one px shorter at the cathode side of the bottom row
        stubs = ((di[0] - 51 - bottom, di[0] - 9),
                 (di[1] + 1, di[1] + 44 - bottom),
                 (dj[0] - 52 - bottom, dj[0] - 10),
                 (dj[1] + 1, dj[1] + 44 - bottom))
        for a, b in stubs:
            hline(y, a, b, SCH_BLUE)
        for dl, dr in (di, dj):
            vline(dl, y - 22, y + 22)
            vline(dr, y - 22, y + 21)
            seg(dl, y - 22, dr, y)
            seg(dl, y + 22, dr, y)
            img[y, dl + 1:dr] = 255
        text(lbl_i, di[0] + 14, y - 44)
        text(lbl_j, dj[0] + 13, y - 44)
        text(diode_label, di[0] + 14, y + 66)
        text(diode_label, dj[0] + 13, y + 66)

    diode_row(ro, layout["d2"], layout["d1"], layout["dot_top"], "D2", "D1", 0)
    diode_row(rg, layout["d3"], layout["d4"], layout["dot_bot"], "D3", "D4", 1)

    # -- R1 row: pin stubs and a 3-tooth zigzag ---------------------------------
    hline(rm, vo, x0 - 44)
    hline(rm, x0 - 43, x0 - 1, SCH_BLUE)
    hline(rm, x0, x0 + 4)
    zz = [(x0 + 4, rm), (x0 + 13, rm - 18), (x0 + 26, rm + 18),
          (x0 + 39, rm - 18), (x0 + 53, rm + 18), (x0 + 66, rm - 18),
          (x0 + 79, rm + 18), (x1, rm)]
    for p, q in zip(zz, zz[1:]):
        seg(*p, *q, last=False)
    hline(rm, x1 + 1, x1 + 43, SCH_BLUE)
    hline(rm, x1 + 44, vm)
    text("R1", x0 + 22, rm - 44)
    text(r_label, x0 + 22, rm + 66)

    # -- shunt capacitor branch (with-capacitor layout only) ---------------------
    if c_label is not None:
        cl, cr = layout["c_branch"]
        p0, p1 = layout["c_plates"]
        cy = layout["c_row"]
        vline(cl, rm, cy)
        vline(cr, rm, cy)
        hline(cy, cl, x0 - 44)
        hline(cy, x0 - 43, x0 - 1, SCH_BLUE)
        hline(cy, x0, p0)
        hline(cy, p1, x1 - 45)               # pixel x1 - 44 is left open
        hline(cy, x1 - 43, x1 - 1, SCH_BLUE)
        hline(cy, x1, cr)
        vline(p0, cy - 22, cy + 21)
        vline(p1, cy - 22, cy + 21)
        text("C1", x0 + 22, cy - 44)
        text(c_label, x0 + 22, cy + 66)

    # -- AC source: circle, sine cycle, polarity marks ---------------------------
    cx = v1x - .5
    for y in range(int(V1_CY - 46), int(V1_CY + 47)):
        dy = y - V1_CY
        if abs(dy) <= V1_R:
            s = math.sqrt(V1_R ** 2 - dy ** 2)
            for x in (cx - s, cx + s):
                img[y, int(math.floor(x + .5))] = SCH_BLUE
    for x in range(int(cx - 46), int(cx + 47)):
        dx = x - cx
        if abs(dx) <= V1_R:
            s = math.sqrt(V1_R ** 2 - dx ** 2)
            for y in (V1_CY - s, V1_CY + s):
                img[int(math.floor(y + .5)), x] = SCH_BLUE
    for dx, ya, yb in SINE_COLUMNS:
        img[ya:yb + 1, v1x + dx] = SCH_BLUE
    cw, ch_, cx0, cy0 = 20, 18, v1x - 9, 374
    plus = np.maximum(
        rect_mark(v1x - .34, v1x + 1.52, 376.58, 389.29, cx0, cy0, cw, ch_),
        rect_mark(v1x - 5.73, v1x + 6.91, 382.0, 383.86, cx0, cy0, cw, ch_))
    blend(_lcd_filter(plus), cx0, cy0, SCH_GREEN)
    blend(_lcd_filter(rect_mark(v1x - 2.85, v1x + 3.5, 454.0, 456.03,
                                v1x - 8, 452, 16, 6)), v1x - 8, 452, SCH_GREEN)
    text("V1", v1x + 23, 374)

    # -- ground: stub and three shrinking bars below the bottom-left junction --
    vline(v1x, 779, 813, SCH_BLUE)
    hline(814, v1x - 22, v1x + 21, SCH_BLUE)
    hline(823, v1x - 13, v1x + 12, SCH_BLUE)
    hline(832, v1x - 4, v1x + 4, SCH_BLUE)

    for x, y in layout["dots"]:
        disc(x, y)

    Image.fromarray(img).save(outpath)


def make_graph(t, vin, vdiff, outpath, kind, dpi, t_window, y_label=Y_LABEL):
    """Probe-style two-trace graph on the shared pspice_theme page (the same
    assembly as plot_full_bridge.make_figure, fed from waveform arrays)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.font_manager import FontProperties

    keep = t <= t_window
    t, vin, vdiff = t[keep], vin[keep], vdiff[keep]
    tmin, tmax = float(t.min()), float(t.max())

    span = max(float(np.abs(vdiff).max()), float(np.abs(vin).max()))
    lim = float(np.ceil(span * 1.1 / 10.0) * 10.0)
    y_step = 50.0 if lim >= 75.0 else (10.0 if lim >= 30.0 else 5.0)
    y_majors = major_ticks(-lim, lim, y_step)
    y_minors = minor_between(y_majors, 5)
    y_labels = [qty_label(v, "V") for v in y_majors]

    tunit = pick_time_unit(tmax)
    xticks = time_ticks(tmin, tmax, 10)
    xlabels = [time_label(x, tunit) for x in xticks]

    fig, ax, frame = new_page((tmin, tmax), (-lim, lim), y_labels)
    style_axes(ax, xticks, xlabels, y_majors, y_labels, y_minors)

    draw_trace(ax, t, vin, frame, PURPLE, "v", 3,
               MARKER_FIRST_PT + MARKER_SPACING_PT / 2)
    draw_trace(ax, t, vdiff, frame, GREEN, "s", 4, MARKER_FIRST_PT)

    installed = {f.name for f in matplotlib.font_manager.fontManager.ttflist}
    prop = FontProperties(family=next(
        (f for f in NOTE_SERIF if f in installed), "serif"))
    fsize = note_fontsize(prop)
    curve_g = dense_curve(t, vdiff, frame)
    curve_p = dense_curve(t, vin, frame)
    both = (np.concatenate([curve_g[0], curve_p[0]]),
            np.concatenate([curve_g[1], curve_p[1]]))
    prefs = GRAPH_PREFS[kind]
    fx, fy, force = prefs[NOTE_VDIFF]
    rect = add_note_at(ax, NOTE_VDIFF, frame, both, [], (fx, fy), fsize, prop,
                       GREEN, force=force)
    fx, fy, force = prefs[NOTE_VIN]
    add_note_at(ax, NOTE_VIN, frame, both, [rect], (fx, fy), fsize, prop,
                PURPLE, force=force)

    add_legend_footer(fig, [("s", GREEN, VDIFF), ("v", PURPLE, VIN)], X_LABEL)
    add_y_label(fig, y_label)

    fig.savefig(outpath, dpi=dpi, facecolor="white")
    plt.close(fig)


# SPICE unit suffixes, case-insensitive ('M' means milli, 'MEG' means mega).
SPICE_SUFFIXES = {"t": 1e12, "g": 1e9, "meg": 1e6, "k": 1e3, "m": 1e-3,
                  "u": 1e-6, "n": 1e-9, "p": 1e-12, "f": 1e-15}


def spice_float(text):
    """Parse a SPICE-style value such as '1meg', '100u' or '10.5'."""
    if isinstance(text, (int, float)):
        return float(text)
    text = text.strip()
    for suf in sorted(SPICE_SUFFIXES, key=len, reverse=True):
        if text.lower().endswith(suf):
            return float(text[:-len(suf)]) * SPICE_SUFFIXES[suf]
    return float(text)


def pspice_value(v):
    """Format a value the way PSpice displays part values (100k, 1Meg, 100u)."""
    for scale, suffix in ((1e6, "Meg"), (1e3, "k"), (1.0, ""), (1e-3, "m"),
                          (1e-6, "u"), (1e-9, "n"), (1e-12, "p")):
        if abs(v) >= scale:
            return f"{v / scale:g}{suffix}"
    return f"{v:g}"


def c_tag(c):
    """File-name tag for a capacitance value (100u, 10u, 470n, ...)."""
    for div, suffix in ((1e-3, "m"), (1e-6, "u"), (1e-9, "n"), (1e-12, "p")):
        if abs(c) >= div:
            return f"{c / div:g}{suffix}"
    return f"{c:g}"


def fmt_farad(c):
    """Capacitance with a sensible unit for table headers."""
    for div, unit in ((1e-3, "mF"), (1e-6, "uF"), (1e-9, "nF"), (1e-12, "pF")):
        if abs(c) >= div:
            return f"{c / div:g} {unit}"
    return f"{c:g} F"


def build_netlist(p, with_cap):
    title = ("Full-Wave Bridge Rectifier with Filter Capacitor" if with_cap
             else "Full-Wave Bridge Rectifier without Filter Capacitor")
    cap_line = f"C1 2 3 {p.c:g}\n" if with_cap else ""
    cycles = p.cycles if p.cycles is not None else (30 if with_cap else 10)
    return NETLIST.format(title=title, vm=p.vm, f=p.f, diode=p.diode,
                          card=p.card, cap_line=cap_line, rl=p.rl,
                          tstep=p.tstep, tstop=p.tstop)


def run_ngspice(p, with_cap, run_dir):
    """Write the netlist, run ngspice in batch mode, return waveform arrays."""
    (run_dir / "bridge.cir").parent.mkdir(parents=True, exist_ok=True)
    (run_dir / "bridge.cir").write_text(build_netlist(p, with_cap))
    log = run_dir / "ngspice.log"
    res = subprocess.run(["ngspice", "-b", "-o", log.name, "bridge.cir"],
                         cwd=run_dir, capture_output=True, text=True)
    data = run_dir / "bridge.data"
    if not data.exists():
        tail = "\n".join(log.read_text(errors="replace").splitlines()[-12:])
        sys.exit(f"ngspice failed (exit {res.returncode}), log tail:\n{tail}")
    return load_wrdata(data)


def load_wrdata(path):
    """Parse a wrdata file: duplicated time column, then value, per vector.

    Returns the three probed node voltages, (t, v(1), v(2), v(3)); node 0 is
    ground. The output is v(2) - v(3) across R1, and the four diode voltages
    follow from the netlist topology as v(1)-v(2), -v(2), v(3)-v(1), v(3)."""
    with open(path) as fh:
        lines = fh.readlines()
    start = 0
    while start < len(lines):
        try:
            [float(x) for x in lines[start].split()]
            break
        except ValueError:
            start += 1
    d = np.loadtxt(lines[start:])
    return d[:, 0], d[:, 1], d[:, 3], d[:, 5]


def freq_from_peaks(t, v, win, period):
    """Output/ripple frequency from well-separated peaks inside the window."""
    tt, vv = t[win], v[win]
    cand = np.where((vv[1:-1] > vv[:-2]) & (vv[1:-1] >= vv[2:]))[0] + 1
    if not len(cand):
        return float("nan")
    kept = []                       # tallest peak wins, half-period exclusion
    for i in cand[np.argsort(vv[cand])[::-1]]:
        if all(abs(tt[i] - tt[j]) > 0.5 * period for j in kept):
            kept.append(i)
    kept.sort()
    if len(kept) < 2:
        return float("nan")
    return 1.0 / np.mean(np.diff(tt[kept]))


def print_table(m, th, rows):
    print(f"{'quantity':>9} | {'simulated':>12} | {'theoretical':>12} | {'% err':>7}")
    print("-" * 50)
    for key, label, scale, fmt in rows:
        if key not in m:
            continue
        s, tv = m[key] * scale, th[key] * scale
        err = abs(tv - s) / abs(tv) * 100
        print(f"{label:>9} | {format(s, fmt):>12} | {format(tv, fmt):>12} |"
              f" {err:6.2f}%")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--vm", type=str, default="100",
                    help="source peak amplitude, V (default 100)")
    ap.add_argument("--f", type=str, default="100",
                    help="source frequency, Hz (default 100)")
    ap.add_argument("--rl", type=str, default="1meg",
                    help="load resistance, ohm (default 1meg)")
    ap.add_argument("--c", type=str, default="100u",
                    help="filter capacitance(s) in F, comma-separated list; "
                         "one filtered-circuit table is printed per value "
                         "(default '100u'; use e.g. '100u,10u' for task 4); "
                         "values accept SPICE suffixes (u, n, m, k, meg)")
    ap.add_argument("--diode", type=str, default="D1N914",
                    help="diode model name (default D1N914; D1N4002 has a "
                         "built-in card)")
    ap.add_argument("--model-card", type=str, default=None,
                    help="raw .MODEL D(...) parameter string override")
    ap.add_argument("--vk", type=float, default=0.7,
                    help="per-diode drop used by the theoretical formulas, V "
                         "(default 0.7, i.e. 2VK = 1.4 V)")
    ap.add_argument("--cycles", type=int, default=None,
                    help="simulated input cycles per circuit (defaults: 10 "
                         "without capacitor, 30 with)")
    ap.add_argument("--tstep", type=str, default="10u",
                    help="transient timestep in s (default 10u)")
    ap.add_argument("--tstop",type=str, default="100m",
                    help="transient stop time")
    ap.add_argument("--meas-cycles", type=int, default=2,
                    help="input periods in the measurement window (default 2)")
    ap.add_argument("--keep", action="store_true",
                    help="keep the generated netlists and ngspice logs in "
                         "ngspice_runs/ instead of a temp directory")
    ap.add_argument("--fig-dir", type=str, default="ngspice_figs",
                    help="directory for the generated graphs and schematics "
                         "(default ngspice_figs)")
    ap.add_argument("--plot-ms", type=str, default="50m",
                    help="time span shown in the graphs, s (default 50m, as "
                         "in the report figures)")
    ap.add_argument("--dpi", type=int, default=260,
                    help="graph output resolution (default 260)")
    ap.add_argument("--no-graphs", action="store_true",
                    help="skip the Probe-style graphs")
    ap.add_argument("--no-schematics", action="store_true",
                    help="skip the capture-style schematics")
    ap.add_argument("--y-label", default=Y_LABEL,
                    help=f"y-axis title for the graphs (default: {Y_LABEL!r})")

    p = ap.parse_args()
    p.vm, p.f, p.rl, p.tstep, p.plot_ms, p.tstop = (spice_float(x) for x in
                                           (p.vm, p.f, p.rl, p.tstep,
                                            p.plot_ms, p.tstop))

    ngspice = shutil.which("ngspice")
    if not ngspice:
        sys.exit("ngspice not found on PATH")
    cards = {"D1N914": D1N914_CARD, "D1N4002": D1N4002_CARD}
    p.card = p.model_card or cards.get(p.diode, GENERIC_CARD)
    if p.model_card is None and p.diode not in cards:
        print(f"note: no built-in card for {p.diode}, using generic "
              f"model: .MODEL {p.diode} D({GENERIC_CARD})")
    caps = [spice_float(x) for x in p.c.replace(",", " ").split()]

    want_figs = not (p.no_graphs and p.no_schematics)
    fig_dir = Path(p.fig_dir)
    if want_figs:
        fig_dir.mkdir(parents=True, exist_ok=True)

    run_root = Path("ngspice_runs") if p.keep else Path(
        tempfile.mkdtemp(prefix="ngspice_bridge_"))
    if p.keep:
        run_root.mkdir(exist_ok=True)

    print(f"ngspice at {ngspice}; Vm = {p.vm:g} V, f = {p.f:g} Hz, "
          f"RL = {p.rl:g} ohm, diode = {p.diode} (2VK = {2 * p.vk:g} V)")
    print("(voltages in V, currents in mA, powers in mW, frequencies in Hz)")

    # ---- circuit 1: without filter capacitor -------------------------------
    t, v1, v2, v3 = run_ngspice(p, False,
                                run_root / "no_cap" if p.keep else run_root)
    vin, vout = v1, v2 - v3
    t_end = t[-1]
    win_len = p.meas_cycles / p.f
    win = (t >= t_end - win_len) & (t <= t_end)
    tt, w = t[win], vout[win]
    dt = tt[-1] - tt[0]
    vdc = np.trapezoid(w, tt) / dt
    vrms = math.sqrt(np.trapezoid(w ** 2, tt) / dt)
    idc, irms = vdc / p.rl, vrms / p.rl
    out_period = 0.5 / p.f
    f0 = freq_from_peaks(t, vout, win, out_period)
    # diode voltages from the netlist topology: D1 1->2, D2 0->2, D3 3->1,
    # D4 3->0, with node 0 at ground; each blocks once per input period
    vdi = [v1[win] - v2[win], -v2[win], v3[win] - v1[win], v3[win]]
    piv_di = [float(np.abs(x).max()) for x in vdi]
    m = {
        "Vm": float(np.abs(vin[win]).max()),
        "2VD": float(np.abs(vin[win]).max()) - w.max(),
        "Vpk": w.max(),
        "Ipk": w.max() / p.rl,
        "Vdc": vdc,
        "Idc": idc,
        "Vrms": vrms,
        "Irms": irms,
        "Pdc": idc ** 2 * p.rl,
        "Pac": irms ** 2 * p.rl,
        "eta": idc ** 2 / irms ** 2 * 100,
        "FF": vrms / vdc,
        "r": math.sqrt((vrms / vdc) ** 2 - 1),
        "PIV": max(piv_di),
        "f0": f0,
    }
    vk2 = 2 * p.vk
    vp = p.vm - vk2
    th = {
        "Vm": p.vm, "2VD": vk2, "Vpk": vp, "Vdc": 2 * vp / math.pi,
        "Vrms": vp / math.sqrt(2), "PIV": p.vm, "f0": 2 * p.f,
    }
    th["Ipk"] = th["Vpk"] / p.rl
    th["Idc"] = th["Vdc"] / p.rl
    th["Irms"] = th["Vrms"] / p.rl
    th["Pdc"] = th["Idc"] ** 2 * p.rl
    th["Pac"] = th["Irms"] ** 2 * p.rl
    th["eta"] = th["Pdc"] / th["Pac"] * 100
    th["FF"] = th["Vrms"] / th["Vdc"]
    th["r"] = math.sqrt(th["FF"] ** 2 - 1)

    print("\n=== without filter capacitor ===")
    print_table(m, th, UNFILTERED_ROWS)
    print(f"  check: PIV per diode D1..D4 = "
          + ", ".join(f"{x:.4f}" for x in piv_di))
    for lo in (t_end - 2 * win_len, t_end - win_len):
        w2 = (t >= lo) & (t <= lo + win_len)
        tt2 = t[w2]
        print(f"  check: Vdc over [{lo * 1e3:.0f},{(lo + win_len) * 1e3:.0f}] "
              f"ms = {np.trapezoid(vout[w2], tt2) / (tt2[-1] - tt2[0]):.4f} V")
    if not p.no_graphs:
        out = fig_dir / "full_bridge.png"
        make_graph(t, vin, vout, out, "no_filter", p.dpi, p.plot_ms, p.y_label)
        print(f"  saved graph {out}")
    if not p.no_schematics:
        out = fig_dir / "schematic_no_filter.png"
        draw_schematic(NO_FILTER_LAYOUT, p.diode, pspice_value(p.rl), None, out)
        print(f"  saved schematic {out}")

    # ---- circuit 2: with filter capacitor ----------------------------------
    count = 0
    for c in caps:
        p.c = c
        t, v1, v2, v3 = run_ngspice(
            p, True, run_root / f"cap_{c:g}" if p.keep else run_root)
        vin, vout = v1, v2 - v3
        t_end = t[-1]
        win = (t >= t_end - win_len) & (t <= t_end)
        tt, w = t[win], vout[win]
        dt = tt[-1] - tt[0]
        vdc = np.trapezoid(w, tt) / dt
        vr_pp = w.max() - w.min()
        # the task-sheet formula Vr(rms) = Vr(pp)/(2*sqrt(3)) applied to the
        # simulated peak-to-peak ripple
        vr_rms = vr_pp / (2.0 * math.sqrt(3))
        fr = freq_from_peaks(t, vout, win, out_period)
        m = {
            "Vc_pk": w.max(),
            "fr": fr,
            "Vr_pp": vr_pp,
            "Vr_rms": vr_rms,
            "Vdc": vdc,
            "IL": vdc / p.rl,
            "r": vr_rms / vdc,
            "pct_r": vr_rms / vdc * 100,
        }
        two_f_cr = 2 * p.f * c * p.rl
        th = {
            "Vc_pk": vp,
            "fr": 2 * p.f,
            "Vdc": vp / (1.0 + 1.0 / (2 * two_f_cr)),
        }
        th["Vr_pp"] = th["Vdc"] / two_f_cr
        th["Vr_rms"] = th["Vr_pp"] / (2 * math.sqrt(3))
        th["IL"] = th["Vdc"] / p.rl
        th["r"] = th["Vr_rms"] / th["Vdc"]
        th["pct_r"] = th["r"] * 100

        print(f"\n=== with filter capacitor, C = {fmt_farad(c)} ===")
        print_table(m, th, FILTERED_ROWS)
        print(f"  check: output valley (capacitor discharge minimum) = "
              f"{w.min():.4f} V")
        for lo in (t_end - 2 * win_len, t_end - win_len):
            w2 = (t >= lo) & (t <= lo + win_len)
            tt2 = t[w2]
            print(f"  check: Vdc over [{lo * 1e3:.0f},"
                  f"{(lo + win_len) * 1e3:.0f}] ms = "
                  f"{np.trapezoid(vout[w2], tt2) / (tt2[-1] - tt2[0]):.4f} V")
        tag = ""
        if count == 1:
            tag = "_changed"
        else:
            tag = ""
        count = count+1

        if not p.no_graphs:
            out = fig_dir / f"full_bridge_with_capacitor{tag}.png"
            make_graph(t, vin, vout, out, "cap", p.dpi, p.plot_ms, p.y_label)
            print(f"  saved graph {out}")
        if not p.no_schematics:
            out = fig_dir / f"schematic_with_capacitor{tag}.png"
            draw_schematic(CAP_LAYOUT, p.diode, pspice_value(p.rl),
                           pspice_value(c), out)
            print(f"  saved schematic {out}")

    if p.keep:
        print(f"\nnetlists and logs kept in {run_root.resolve()}")


if __name__ == "__main__":
    main()
