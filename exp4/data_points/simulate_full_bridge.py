#!/usr/bin/env python3
"""
Simulate the exp4 full-wave bridge rectifier circuits with ngspice, print
every characteristic parameter of the task-sheet tables, and render the
report figures (Probe-style graphs and capture-style schematics).

The netlists are generated from the given parameters (source amplitude and
frequency, load resistance, filter capacitance, diode model); ngspice runs
in batch mode on both circuits, one without and one with the shunt
capacitor, and the values are extracted from the simulated waveforms:

  * without filter capacitor: peak input voltage Vm, total diode voltage drop
    2VK, peak output voltage Vo(pk) and current Io(pk), DC and RMS output
    voltage and load current, DC and AC load power, rectification efficiency,
    ripple factor, form factor, peak inverse voltage per diode (largest
    magnitude of any diode voltage over the last input period), and output
    frequency f0 = 2f;
  * with filter capacitor: peak capacitor voltage Vc(pk), ripple frequency
    fr, peak-to-peak ripple voltage, RMS ripple voltage, DC output voltage,
    load current, ripple factor and percentage ripple. Vr(rms) is evaluated
    with the task-sheet formula Vr(rms) = Vr(pp)/(2*sqrt(3)) applied to the
    simulated Vr(pp), exactly as the table specifies. Multiple capacitances
    may be given (task 4's modified circuit is --c 10u).

Theoretical values use the task-sheet formulas with two conducting silicon
diodes (2VK = 1.4 V by default, see --vk). For the filtered circuit the
sheet's approximations Vr(pp) = IL/(2fC), Vdc = Vc(pk) - Vr(pp)/2 and
IL = Vdc/R are solved simultaneously, giving Vdc = Vc(pk)/(1 + 1/(4fCR)) and
Vr(pp) = Vdc/(2fCR), which reproduces every formula of the with-capacitor
table consistently (the ripple factor then reduces to
r = 1/(4*sqrt(3)*f*C*R)).

Measurements are taken over the last --meas-cycles input periods (default 2,
i.e. the last 20 ms at 100 Hz). Output rows, units and formatting match
measure_full_bridge.py: voltages in V, currents in mA, powers in mW,
frequencies in Hz. Diagnostics after each table: the PIV of each individual
diode and the DC level over the preceding measurement windows (a
steady-state check).

Figures, written into --fig-dir (default ngspice_figs/):
  * one Probe-style graph per circuit, drawn on the shared pspice_theme page
    with the same two-trace styling as plot_full_bridge.py (V(R1:1,R1:2) in
    green with white square markers over V(1) in violet with white triangle
    markers, framed serif notes "Voltage across resistor"/"Vin", hollow
    marker legend and the "Time (ms)" axis label at the foot); the first
    --plot-ms milliseconds are shown, as in the report figures;
  * one capture-style schematic per circuit, rendered pixel by pixel to
    reproduce the report's schematic_*.png reference figures almost exactly:
    1-px aliased green wires and blue pin stubs, blue junction discs, the
    single-pixel grey capture grid, and LCD (sub-pixel) filtered Liberation
    Sans labels; the diode model, R and C labels come from the given
    parameters.

ngspice prints "Warning: d1n914: IKF too small - model effect disabled!" for
the report's card (Ikf=0); the effect is disabled in every simulator at
Ikf=0, so the warning can be ignored. The log is only shown if ngspice fails.

Requires ngspice on PATH (tested with ngspice-47) plus matplotlib (and Pillow,
which it installs) with the
companion pspice_theme.py and plot_full_bridge.py modules beside this script.
"""

